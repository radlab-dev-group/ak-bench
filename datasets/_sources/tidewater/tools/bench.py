#!/usr/bin/env python3
"""Measure what a simulation costs, in CPU time and in allocations.

::

    python tools/bench.py --schedule schedules/baseline-steady.json
    python tools/bench.py --ticks 6000 --nodes 5 --seed 42
    python tools/bench.py --schedule schedules/long-haul.json --json-out /tmp/bench.json

The number that matters is ``cpu_seconds``: wall time includes everything the
machine does while the process is not running, which is not the simulator's
cost and is the reason two runs on two machines differ. ``process_time``
counts only this process's CPU, and the allocation counters come from
``tracemalloc`` around the run, so they are the simulator's and not the
operating system's.

A benchmark that is not reproducible is a rumour, so the tool reports what it
did as well as what it measured: the schedule or the generated one, its seed,
its length, and the number of ticks actually run. ``--json-out`` writes the
whole record to a file for a harness to read, and ``--json`` prints it.
"""

from __future__ import annotations

import argparse
import gc
import json
import pathlib
import sys
import time
import tracemalloc

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from tidewater.cluster import run_schedule  # noqa: E402
from tidewater.schedule import load_schedule, nodes_named, schedule_from_dict  # noqa: E402


def generated_schedule(name: str, nodes: int, ticks: int, seed: int) -> Schedule:
    """A plain cluster with a steady workload: the benchmark's own schedule.

    No faults, no partitions — the cost being measured is the protocol's, and
    a fault would put the measurement somewhere else. The workload is one
    write every ten ticks, which keeps the log growing the way a real cluster
    grows it and leaves the election timers to do their ordinary work.
    """

    return schedule_from_dict(
        {
            "schema": 1,
            "name": name,
            "description": "generated by tools/bench.py",
            "nodes": list(nodes_named(nodes)),
            "seed": seed,
            "ticks": ticks,
            "actions": [
                {
                    "at": 10,
                    "kind": "workload",
                    "count": max(1, (ticks - 10) // 10),
                    "every": 10,
                    "key_prefix": "w",
                }
            ],
        }
    )


def bench(schedule: Schedule, *, ticks: int | None = None) -> dict:
    """Run the simulation once, measuring what it costs.

    ``ticks`` shortens the run without touching the schedule's own length;
    the measured fields are the run's, and the record says which one it was.
    The allocation counters are the difference of the peak and the total,
    which is what a run *adds*, and that is the number an optimisation is
    judged against.
    """

    gc.collect()
    tracemalloc.start()
    started = time.process_time()
    result = run_schedule(schedule, ticks=ticks)
    cpu = time.process_time() - started
    current, peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()

    return {
        "schedule": schedule.name,
        "seed": result.seed,
        "ticks": result.ticks,
        "nodes": len(schedule.nodes),
        "events": result.events,
        "cpu_seconds": round(cpu, 6),
        "traced_bytes_peak": peak,
        "traced_bytes_live": current,
        "digest": result.digest,
        "violation": result.violation.kind if result.violation else None,
        "accepted": result.proposals["accepted"],
        "offered": result.proposals["offered"],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="bench", description=__doc__.splitlines()[0])
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--schedule", type=pathlib.Path, help="a schedule file to measure")
    source.add_argument("--nodes", type=int, default=5, help="cluster size for the generated schedule")
    parser.add_argument("--ticks", type=int, help="run length; the schedule's length by default")
    parser.add_argument("--seed", type=int, default=42, help="seed for the generated schedule")
    parser.add_argument("--json", action="store_true", help="print the record as JSON")
    parser.add_argument("--json-out", type=pathlib.Path, help="also write the record to a file")
    args = parser.parse_args(argv)

    if args.schedule is not None:
        schedule = load_schedule(args.schedule)
        if args.ticks is not None:
            schedule = schedule_from_dict(
                {
                    **schedule.to_dict(),
                    "ticks": args.ticks,
                    "actions": [
                        a.to_dict() for a in schedule.expanded_actions() if a.at < args.ticks
                    ],
                }
            )
    else:
        schedule = generated_schedule("bench", args.nodes, args.ticks or 2000, args.seed)

    record = bench(schedule, ticks=args.ticks)
    if args.json:
        print(json.dumps(record, indent=2, sort_keys=True))
    else:
        print(
            f"{record['schedule']} seed={record['seed']} ticks={record['ticks']} "
            f"nodes={record['nodes']}: {record['cpu_seconds']:.3f}s cpu, "
            f"{record['events']} events, peak {record['traced_bytes_peak']} bytes traced"
        )
    if args.json_out is not None:
        args.json_out.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
